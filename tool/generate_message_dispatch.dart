import 'dart:convert';
import 'dart:io';

/// Connect Spanish source copy to Flutter's generated, typed ARB accessors.
/// Run from the app root before `flutter gen-l10n` after adding messages.
void main() {
  final catalog =
      jsonDecode(File('lib/l10n/app_es.arb').readAsStringSync())
          as Map<String, dynamic>;
  final lines = <String>[];
  final sources = <String>{};
  for (final key in catalog.keys.where((key) => !key.startsWith('@'))) {
    final metadata = catalog['@$key'] as Map<String, dynamic>? ?? {};
    final source = metadata['description'] as String? ?? catalog[key] as String;
    if (!sources.add(source)) {
      throw StateError('Duplicate Spanish source: $source');
    }
    final placeholders =
        metadata['placeholders'] as Map<String, dynamic>? ?? {};
    var getter = 'l.$key';
    if (placeholders.isNotEmpty) {
      final arguments = placeholders.entries.map((entry) {
        final type = (entry.value as Map<String, dynamic>)['type'] ?? 'Object';
        return type == 'String'
            ? "values['${entry.key}'].toString()"
            : "values['${entry.key}'] as $type";
      });
      getter += '(${arguments.join(', ')})';
    }
    final literal = jsonEncode(source).replaceAll(r'$', r'\$');
    lines.add('    $literal => $getter,');
  }
  File('lib/l10n/messages.dart').writeAsStringSync(
    "// Generated by tool/generate_message_dispatch.dart. Edit the ARB files.\n"
    "import 'generated/app_localizations.dart';\n\n"
    'String message(AppLocalizations l, String source, Map<String, Object?> values) => switch (source) {\n'
    '${lines.join('\n')}\n'
    '    _ => source,\n'
    '  };\n',
  );
  stdout.writeln('Generated ${lines.length} message accessors.');
}
